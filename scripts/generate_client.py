"""Generate the client mixins and the models module from the endpoint registry.

Run ``uv run python scripts/generate_client.py``. ``tests/test_surface.py`` fails when the
committed files differ from what this produces. The package ``__init__`` is skipped, so the
script still runs when a generated file names a module that was renamed or removed.
"""

from __future__ import annotations

import sys
import textwrap
import types
from collections.abc import Iterable, Sequence
from dataclasses import is_dataclass
from datetime import date, datetime
from pathlib import Path
from typing import (
    Annotated,
    Any,
    Literal,
    NamedTuple,
    Union,
    cast,
    get_args,
    get_origin,
    get_type_hints,
)

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "src" / "xueqiu_api"
WIDTH = 100
CODE_PARAMS = frozenset(
    {"symbol", "symbols", "fund_code", "index_code", "cube_symbol", "cube_symbols"}
)
"""Parameters that may be positional when they come first; everything else is keyword-only."""
HEADER = "# Generated by scripts/generate_client.py from the endpoint registry. Do not edit."
DOC = "One method per endpoint, and ``<name>_pages`` where the list has numbered pages."

if "xueqiu_api" not in sys.modules:
    stub = types.ModuleType("xueqiu_api")
    stub.__path__ = [str(PACKAGE)]
    sys.modules["xueqiu_api"] = stub

from pydantic import AwareDatetime, BaseModel, BeforeValidator  # noqa: E402
from pydantic.fields import FieldInfo  # noqa: E402

from xueqiu_api.endpoints import REGISTRY  # noqa: E402
from xueqiu_api.registry import Endpoint  # noqa: E402
from xueqiu_api.symbols import split_symbols  # noqa: E402


class Imports:
    """Names to import, by module, written the way ruff's isort sorts them."""

    def __init__(self) -> None:
        self.names: dict[str, set[str]] = {}

    def add(self, module: str, name: str) -> str:
        self.names.setdefault(module, set()).add(name)
        return name

    def of(self, cls: type) -> str:
        if cls.__module__ == "builtins":
            return cls.__name__
        return self.add(_relative(cls.__module__), cls.__name__)


class Param(NamedTuple):
    name: str
    annotation: str
    default: str | None
    """Source text of the default; None when the param is required."""


def _relative(module: str) -> str:
    return module.removeprefix("xueqiu_api")


def _literal_name(tp: Any, module: str) -> str | None:
    """The public alias of a Literal in ``module``."""
    for key, value in vars(sys.modules[module]).items():
        if not key.startswith("_") and get_origin(value) is Literal and value == tp:
            return key
    return None


def _render(tp: Any, module: str, imports: Imports) -> str:
    """``tp`` as source text; Literal aliases are looked up in ``module``."""
    origin = get_origin(tp)
    if origin is Annotated:
        return _render(get_args(tp)[0], module, imports)
    if tp is None or tp is type(None):
        return "None"
    if origin is Literal:
        name = _literal_name(tp, module)
        if name is None:
            raise TypeError(f"{tp!r} in a signature needs a public alias in {module}")
        return imports.add(_relative(module), name)
    if origin in (Union, types.UnionType):
        return " | ".join(_render(arg, module, imports) for arg in get_args(tp))
    if isinstance(origin, type):
        args = ", ".join(
            "..." if arg is Ellipsis else _render(arg, module, imports) for arg in get_args(tp)
        )
        return f"{imports.of(origin)}[{args}]"
    if tp is AwareDatetime or tp is datetime:
        return imports.add("datetime", "datetime")
    if tp is date:
        return imports.add("datetime", "date")
    if isinstance(tp, type) and tp is not Any:
        return imports.of(tp)
    raise TypeError(f"cannot write {tp!r} in a signature")


def _public_type(field: FieldInfo, module: str, imports: Imports) -> str:
    """What a caller passes: the validated type, except where a validator accepts more."""
    if any(isinstance(m, BeforeValidator) and m.func is split_symbols for m in field.metadata):
        imports.add("collections.abc", "Sequence")
        return "str | Sequence[str]"
    return _render(field.annotation, module, imports)


def _params(spec: Endpoint[Any, Any], imports: Imports) -> list[Param]:
    module = spec.params.__module__
    params: list[Param] = []
    for name, field in spec.params.model_fields.items():
        if field.default_factory is not None:
            raise ValueError(f"{spec.name}.{name}: a default factory cannot appear in a signature")
        default = None if field.is_required() else repr(field.default).replace("'", '"')
        params.append(Param(name, _public_type(field, module, imports), default))
    return params


def _page_params(params: Sequence[Param]) -> list[Param]:
    """The params of ``<name>_pages``: no page size means the largest, and two walk limits."""
    limits = [Param(name, "int | None", "None") for name in ("max_pages", "max_items")]
    return [
        Param(param.name, "int | None", "None") if param.name == "page_size" else param
        for param in params
    ] + limits


def _signature(name: str, params: Sequence[Param], returns: str, prefix: str = "") -> list[str]:
    parts = ["self"]
    for index, param in enumerate(params):
        if (index > 0 or param.name not in CODE_PARAMS) and "*" not in parts:
            parts.append("*")
        text = f"{param.name}: {param.annotation}"
        parts.append(text if param.default is None else f"{text} = {param.default}")
    one_line = f"    {prefix}def {name}({', '.join(parts)}) -> {returns}:"
    if len(one_line) <= WIDTH:
        return [one_line]
    return [
        f"    {prefix}def {name}(",
        *(f"        {part}," for part in parts),
        f"    ) -> {returns}:",
    ]


def _docstring(spec: Endpoint[Any, Any], *, pages: bool) -> list[str]:
    first = f"{spec.agent.title_zh}: {spec.doc}"
    if pages:
        first = f"Every page of ``{spec.name}``, one request each. {first}"
    lines = textwrap.wrap(first, 90)
    if spec.params.__module__.endswith(f".{spec.name}") and spec.params.__doc__:
        lines += ["", *(line.strip() for line in spec.params.__doc__.strip().splitlines())]
    args = {
        name: " ".join((field.description or "").split())
        for name, field in spec.params.model_fields.items()
    }
    if pages and spec.pagination is not None:
        if "page_size" in args:
            cap = spec.pagination.size_cap
            args["page_size"] = f"Rows per page; by default the largest, {cap}."
        args["max_pages"] = "Stop after this many pages."
        args["max_items"] = "Stop after this many rows; the last page is cut to fit."
    if any(args.values()):
        lines += ["", "Args:"]
        for name, text in args.items():
            if text:
                wrapped = textwrap.wrap(f"{name}: {text}", 86)
                lines += [f"    {wrapped[0]}", *(f"        {part}" for part in wrapped[1:])]
    lines += ["", f"Auth {spec.auth}; freshness {spec.freshness}."]
    return [
        f'        """{lines[0]}',
        *(f"        {line}" if line else "" for line in lines[1:]),
        '        """',
    ]


def _body(
    call: str, constant: str, params: Sequence[Param], limits: Sequence[str] = ()
) -> list[str]:
    pairs = [f'"{param.name}": {param.name}' for param in params]
    mapping = "{" + ", ".join(pairs) + "}"
    one_line = f"        return {call}({', '.join([constant, mapping, *limits])})"
    if len(one_line) <= WIDTH:
        return [one_line]
    together = f"            {mapping},"
    return [
        f"        return {call}(",
        f"            {constant},",
        *(
            [together]
            if len(together) <= WIDTH
            else [
                "            {",
                *(f"                {pair}," for pair in pairs),
                "            },",
            ]
        ),
        *(f"            {limit}," for limit in limits),
        "        )",
    ]


def _import_key(name: str) -> tuple[int, str]:
    # isort's order within an import: CONSTANTS, then Classes, then functions.
    bare = name.split(" as ")[0]
    rank = 0 if bare.isupper() else 1 if bare[0].isupper() else 2
    return rank, bare


def _import_block(imports: Imports, modules: Iterable[str]) -> list[str]:
    out: list[str] = []
    for module in modules:
        names = sorted(imports.names[module], key=_import_key)
        out += [f"from {module} import {name}" for name in names if " as " in name]
        plain = [name for name in names if " as " not in name]
        line = f"from {module} import {', '.join(plain)}"
        if not plain:
            continue
        if len(line) <= WIDTH:
            out.append(line)
        else:
            out += [f"from {module} import (", *(f"    {name}," for name in plain), ")"]
    return out


def _import_lines(imports: Imports) -> list[str]:
    local = [module for module in imports.names if module.startswith(".")]
    others = [module for module in imports.names if not module.startswith(".")]
    groups = [
        sorted(module for module in others if module != "pydantic"),
        sorted(module for module in others if module == "pydantic"),
        sorted(local, key=str.lower),
    ]
    lines: list[str] = []
    for group in groups:
        if group:
            lines += [*_import_block(imports, group), ""]
    return lines[:-1]


def _mixin(kind: Literal["sync", "async"]) -> str:
    imports = Imports()
    imports.add("collections.abc", "Mapping")
    imports.add("typing", "TYPE_CHECKING")
    imports.add("typing", "Any")
    imports.add("typing", "TypeVar")
    imports.add("pydantic", "BaseModel")
    imports.add(".registry", "Endpoint")
    imports.add("._pages", "PageT")
    is_async = kind == "async"
    iterator = imports.add("collections.abc", "AsyncIterator" if is_async else "Iterator")
    prefix, await_ = ("async ", "await ") if is_async else ("", "")
    body: list[str] = []
    for name, spec in REGISTRY.items():
        constant = name.upper()
        imports.add(f".endpoints.{name}", f"ENDPOINT as {constant}")
        params = _params(spec, imports)
        returns = _render(get_type_hints(spec.parse)["return"], spec.parse.__module__, imports)
        body += ["", *_signature(name, params, returns, prefix), *_docstring(spec, pages=False)]
        body += _body(f"{await_}self._call", constant, params)
        if spec.pagination is None or spec.pagination.style != "page":
            continue
        signature = _signature(f"{name}_pages", _page_params(params), f"{iterator}[{returns}]")
        body += ["", *signature, *_docstring(spec, pages=True)]
        limits = ("max_pages=max_pages", "max_items=max_items")
        body += _body("self._pages", constant, params, limits)
    cls = "AsyncEndpoints" if is_async else "SyncEndpoints"
    return "\n".join(
        [
            HEADER,
            "",
            "from __future__ import annotations",
            "",
            *_import_lines(imports),
            "",
            'P = TypeVar("P", bound=BaseModel)',
            'R = TypeVar("R")',
            "",
            "",
            f"class {cls}:",
            f'    """{DOC}"""',
            "",
            "    if TYPE_CHECKING:",
            "",
            f"        {prefix}def _call(self, spec: Endpoint[P, R], "
            "params: Mapping[str, Any]) -> R: ...",
            "",
            "        def _pages(",
            "            self,",
            "            spec: Endpoint[P, PageT],",
            "            params: Mapping[str, Any],",
            "            *,",
            "            max_pages: int | None = None,",
            "            max_items: int | None = None,",
            f"        ) -> {iterator}[PageT]: ...",
            *body,
            "",
        ]
    )


def _is_result_class(tp: Any) -> bool:
    if not isinstance(tp, type):
        return False
    cls = cast(type[Any], tp)
    return issubclass(cls, BaseModel) or is_dataclass(cls) or hasattr(cls, "_fields")


def _field_types(cls: type[Any]) -> list[Any]:
    if issubclass(cls, BaseModel):
        return [field.annotation for field in cls.model_fields.values()]
    return list(get_type_hints(cls).values())


def _add_public(found: dict[str, tuple[Any, str]], name: str, value: Any, module: str) -> None:
    seen = found.setdefault(name, (value, module))
    if seen[0] is not value:
        raise ValueError(f"two public types are named {name}: in {seen[1]} and in {module}")


def _walk(tp: Any, module: str, found: dict[str, tuple[Any, str]]) -> None:
    origin = get_origin(tp)
    if origin is Literal:
        name = _literal_name(tp, module)
        if name is not None:
            _add_public(found, name, vars(sys.modules[module])[name], module)
    elif origin is not None:
        if _is_result_class(origin):
            _walk(origin, module, found)
        for part in get_args(tp):
            _walk(part, module, found)
    elif _is_result_class(tp):
        if found.get(tp.__name__, (None,))[0] is tp:
            return
        _add_public(found, tp.__name__, tp, tp.__module__)
        # A subclass of Page[Row] names its row type only among its bases.
        for hint in (*getattr(tp, "__orig_bases__", ()), *_field_types(tp)):
            _walk(hint, tp.__module__, found)


def public_types(specs: Iterable[Endpoint[Any, Any]]) -> dict[str, tuple[Any, str]]:
    """Name to type and module of each result class and named Literal callers can meet.

    Raises ``ValueError`` when one name would mean two types.
    """
    found: dict[str, tuple[Any, str]] = {}
    for spec in specs:
        for field in spec.params.model_fields.values():
            _walk(field.annotation, spec.params.__module__, found)
        _walk(get_type_hints(spec.parse)["return"], spec.parse.__module__, found)
    return found


def _models() -> str:
    found = public_types(REGISTRY.values())
    imports = Imports()
    for name, (_, module) in found.items():
        imports.add(_relative(module), name)
    return "\n".join(
        [
            HEADER,
            '"""The result models and public Literal types of the endpoint methods."""',
            "",
            *_import_lines(imports),
            "",
            "__all__ = [",
            *(f'    "{name}",' for name in sorted(found, key=_import_key)),
            "]",
            "",
        ]
    )


def generate() -> dict[Path, str]:
    return {
        PACKAGE / "_endpoints_sync.py": _mixin("sync"),
        PACKAGE / "_endpoints_async.py": _mixin("async"),
        PACKAGE / "models.py": _models(),
    }


if __name__ == "__main__":
    for path, text in generate().items():
        path.write_text(text, encoding="utf-8", newline="\n")
        print(path)
